String tr(String text,String lang){
  if(lang!='en')return text;
  final messages=Catalog.source['messages'] as Map? ?? {};
  final exact=_nativeEn[text]??messages[text] as String?;if(exact!=null)return exact;
  if(RegExp(r'^Paso \d+ de \d+$').hasMatch(text))return text.replaceFirst('Paso ','Step ').replaceFirst(' de ',' of ');
  if(text.startsWith('Hola, '))return text.replaceFirst('Hola, ','Hi, ');
  if(text.startsWith('Últimos 30 días · '))return text.replaceFirst('Últimos 30 días','Last 30 days');
  if(text.startsWith('Ingresos · '))return text.replaceFirst('Ingresos · ','Income · ').replaceFirst('30 días','30 days');
  if(text.startsWith('Egresos · '))return text.replaceFirst('Egresos · ','Outgoings · ').replaceFirst('30 días','30 days');
  return text;
}
String t(String text)=>tr(text,Catalog.lang);

/// A native Text widget using the same message catalog as the website.
class Text extends material.StatelessWidget {
  const Text(this.data,{super.key,this.style,this.strutStyle,this.textAlign,
    this.textDirection,this.locale,this.softWrap,this.overflow,this.textScaler,
    this.maxLines,this.semanticsLabel,this.textWidthBasis,this.textHeightBehavior,
    this.selectionColor});
  final String data;
  final material.TextStyle? style;final material.StrutStyle? strutStyle;
  final material.TextAlign? textAlign;final material.TextDirection? textDirection;
  final material.Locale? locale;final bool? softWrap;final material.TextOverflow? overflow;
  final material.TextScaler? textScaler;final int? maxLines;final String? semanticsLabel;
  final material.TextWidthBasis? textWidthBasis;final material.TextHeightBehavior? textHeightBehavior;
  final material.Color? selectionColor;
  @override material.Widget build(material.BuildContext context){
    final lang=material.Localizations.localeOf(context).languageCode;
    var effective=style;
    if(material.Theme.of(context).brightness==material.Brightness.dark){
      final c=style?.color;
      if(c==const material.Color(0xff12312f)||c==const material.Color(0xff0b3d3b))effective=style!.copyWith(color:const material.Color(0xffeaf3f2));
      if(c==const material.Color(0xff4c6a67))effective=style!.copyWith(color:const material.Color(0xffb9d4d1));
      if(c==material.Colors.red.shade800)effective=style!.copyWith(color:material.Colors.red.shade200);
    }
    return material.Text(tr(data,lang),style:effective,strutStyle:strutStyle,textAlign:textAlign,
      textDirection:textDirection,locale:locale,softWrap:softWrap,overflow:overflow,
      textScaler:textScaler,maxLines:maxLines,semanticsLabel:semanticsLabel,
      textWidthBasis:textWidthBasis,textHeightBehavior:textHeightBehavior,selectionColor:selectionColor);
  }
}
